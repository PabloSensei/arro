//! The About window: the version of this build, what the product is, and the way to a bug
//! report. It is a modal view of the workspace, without a web view of its own.

use std::path::PathBuf;

use ::platform::{open_url, resources_dir};
use ui_kit::metrics::*;
use ui_kit::prelude::*;
use ui_kit::*;

use crate::launch::AppInfo;
use crate::window::Workspace;

const WIDTH: f32 = 500.;
const SUPPORT_URL: &str = "https://github.com/sponsors/PabloSensei";

/// The files of the distribution that sit next to the executable.
const NOTICES: [&str; 2] = ["THIRD-PARTY.txt", "NOTICE.txt"];

pub struct AboutView {
    info: AppInfo,
    workspace: WeakEntity<Workspace>,
    focus: FocusHandle,
    notices: Vec<PathBuf>,
}

impl AboutView {
    pub fn show(workspace: &mut Workspace, window: &mut Window, cx: &mut Context<Workspace>) {
        let info = *workspace.info();
        let weak = cx.weak_entity();
        let notices = notice_files();
        let view = cx.new(|cx| Self {
            info,
            workspace: weak,
            focus: cx.focus_handle(),
            notices,
        });
        let focus = view.read(cx).focus.clone();
        workspace.show_overlay(view.into(), focus, window, cx);
    }

    pub fn info(&self) -> &AppInfo {
        &self.info
    }

    /// What the window shows, line by line.
    pub fn lines(&self) -> Vec<String> {
        vec![
            format!("{} {}", self.info.name, self.info.version),
            format!("Channel: {}  Commit: {}", self.info.channel, self.info.commit),
            format!("Built: {}", self.info.date),
            "Early preview. Expect rough edges and missing features.".to_owned(),
            "Written with AI: most of the code is generated by language models and reviewed by a human."
                .to_owned(),
            "Licensed under FSL-1.1-ALv2.".to_owned(),
        ]
    }

    /// The line the Copy button puts on the clipboard.
    pub fn copy_line(&self) -> String {
        self.info.report_line()
    }

    /// Whether the notices of the distribution are next to the executable.
    pub fn has_notices(&self) -> bool {
        !self.notices.is_empty()
    }

    fn close(&mut self, window: &mut Window, cx: &mut Context<Self>) {
        self.workspace
            .update(cx, |workspace, cx| workspace.dismiss(window, cx))
            .ok();
    }

    fn copy(&mut self, cx: &mut Context<Self>) {
        let line = self.copy_line();
        cx.write_to_clipboard(ClipboardItem::new_string(line));
    }

    fn open_notices(&mut self) {
        for path in &self.notices {
            open_url(&path.display().to_string());
        }
    }

    fn key(&mut self, event: &KeyDownEvent, window: &mut Window, cx: &mut Context<Self>) {
        match event.keystroke.key.as_str() {
            "escape" => self.close(window, cx),
            "enter" => self.close(window, cx),
            _ => return,
        }
        cx.stop_propagation();
    }
}

/// `THIRD-PARTY.txt` and `NOTICE.txt` in the resources of the program, when they exist.
fn notice_files() -> Vec<PathBuf> {
    let Ok(program) = std::env::current_exe() else {
        return Vec::new();
    };
    let folder = resources_dir(&program);
    NOTICES
        .iter()
        .map(|name| folder.join(name))
        .filter(|path| path.is_file())
        .collect()
}

fn dialog_button(
    id: &'static str,
    label: &'static str,
    primary: bool,
    enabled: bool,
    theme: &Theme,
) -> Stateful<Div> {
    let (hover, pressed) = (theme.hover, theme.pressed);
    div()
        .id(id)
        .flex()
        .items_center()
        .h(px(CONTROL_HEIGHT))
        .px(px(SPACE_L))
        .rounded(px(CONTROL_RADIUS))
        .when(primary && enabled, |this| {
            this.bg(theme.accent).text_color(theme.over_accent)
        })
        .when(!primary && enabled, |this| {
            this.border_1()
                .border_color(theme.control_border)
                .hover(move |style| style.bg(hover))
                .active(move |style| style.bg(pressed))
        })
        .when(!enabled, |this| this.text_color(theme.text_muted))
        .child(label)
}

fn action(id: &'static str, label: &'static str, theme: &Theme) -> Stateful<Div> {
    dialog_button(id, label, false, true, theme).debug_selector(move || format!("about-{id}"))
}

impl Render for AboutView {
    fn render(&mut self, window: &mut Window, cx: &mut Context<Self>) -> impl IntoElement {
        let theme = *cx.global::<Theme>();
        let viewport = window.viewport_size();
        let width = px(WIDTH);
        let left = (viewport.width - width) / 2.;
        let top = viewport.height * 0.2;
        let lines = self.lines();
        let notices = dialog_button(
            "about-notices",
            "Third-Party Notices",
            false,
            self.has_notices(),
            &theme,
        )
        .debug_selector(|| "about-notices".to_owned())
        .when(self.has_notices(), |this| {
            this.on_click(cx.listener(|this, _, _, _| this.open_notices()))
        });
        let body = surface(&theme)
            .id("about")
            .track_focus(&self.focus)
            .occlude()
            .w(width)
            .p(px(DIALOG_PADDING))
            .gap(px(DIALOG_GAP))
            .text_size(px(UI_SIZE))
            .text_color(theme.text)
            .on_key_down(cx.listener(|this, event, window, cx| this.key(event, window, cx)))
            .on_mouse_down_out(cx.listener(|this, _, window, cx| this.close(window, cx)))
            .child(
                img("brand/arro.svg")
                    .size(px(64.))
                    .flex_none()
                    .debug_selector(|| "about-logo".to_owned()),
            )
            .child(
                div()
                    .font_weight(FontWeight::SEMIBOLD)
                    .text_size(px(18.))
                    .child(format!("{} {}", self.info.name, self.info.version)),
            )
            .children(lines.into_iter().skip(1).map(|line| {
                div()
                    .text_color(theme.text_secondary)
                    .child(SharedString::from(line))
            }))
            .child(
                div()
                    .mt(px(DIALOG_GAP))
                    .flex()
                    .flex_wrap()
                    .gap(px(SPACE_M))
                    .child(action("copy", "Copy", &theme).on_click(cx.listener(
                        |this, _, _, cx| {
                            this.copy(cx);
                            cx.notify();
                        },
                    )))
                    .child(notices)
                    .child(
                        action("support", "Support Arro", &theme).on_click(cx.listener(
                            |_, _, _, _| {
                                open_url(SUPPORT_URL);
                            },
                        )),
                    )
                    .child(
                        dialog_button("about-close", "Close", true, true, &theme)
                            .debug_selector(|| "about-close".to_owned())
                            .on_click(cx.listener(|this, _, window, cx| this.close(window, cx))),
                    ),
            );
        div()
            .absolute()
            .left(left)
            .top(top)
            .child(enter("about-enter", body))
    }
}
